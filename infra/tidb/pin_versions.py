#!/usr/bin/env python3
"""Pin TiDB-ecosystem component tarballs (version, sha256, size) into third_party/tidb/VERSIONS.

    python3 infra/tidb/pin_versions.py --tidb-version v8.5.8            # write the file
    python3 infra/tidb/pin_versions.py --tidb-version v8.5.8 --check    # compare, exit 1 on drift

Source of truth is PingCAP's TiUP mirror (https://tiup-mirrors.pingcap.com): each component has a
manifest listing, per platform and version, the tarball URL, sha256 and length. This tool records
those values so the repo pins *exact artifacts*; ``fetch_tidb.sh`` then refuses any tarball whose
hash differs from the pin. It does not verify the mirror's TUF signatures (TiUP does that itself at
install time); the protection here is HTTPS plus hash pinning against drift.

Components pinned at the TiDB version: tidb, tikv, pd, ctl (pd-ctl), prometheus, grafana.
Components pinned at their own latest non-yanked release: tiup, cluster. Exporters
(node_exporter, blackbox_exporter, alertmanager) are chosen by tiup-cluster and are pinned in
exec #7 step 4 once the versions it selects are known.

Standard library only; runs anywhere with Python 3.9+.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import urllib.request
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OUT = ROOT / "third_party" / "tidb" / "VERSIONS"
MIRROR = "https://tiup-mirrors.pingcap.com"
PLATFORM = "linux/amd64"  # i4i.2xlarge and the controller are x86

AT_TIDB_VERSION = ["tidb", "tikv", "pd", "ctl", "prometheus", "grafana"]
AT_LATEST = ["tiup", "cluster"]

HEADER = """\
# Pinned TiDB-ecosystem artifacts for Powder (exec #7). Generated by infra/tidb/pin_versions.py.
# Columns: component  version  platform  sha256  bytes  url (relative to the mirror)
# The `tidb` row's version is THE TiDB version of the repo; every experiment records it in its manifest.
# Change versions by re-running pin_versions.py and committing the diff; never edit hashes by hand.
# Mirror: {mirror}   mirror timestamp version: {snapshot}   pinned: {today}
"""


def fetch_json(url: str) -> dict:
    with urllib.request.urlopen(url, timeout=60) as r:  # noqa: S310 (https mirror, fixed host)
        return json.load(r)


def semver(v: str):
    m = re.fullmatch(r"v(\d+)\.(\d+)\.(\d+)", v)
    return tuple(int(x) for x in m.groups()) if m else None


def latest_release(platform_entries: dict) -> str:
    """Highest plain vX.Y.Z (no pre/nightly suffix) that is not yanked."""
    candidates = [
        (semver(v), v) for v, e in platform_entries.items() if semver(v) and not e.get("yanked")
    ]
    if not candidates:
        raise ValueError("no released (non-yanked, plain vX.Y.Z) version found")
    return max(candidates)[1]


def pick_entry(manifest: dict, component: str, version: str | None, platform: str = PLATFORM) -> tuple[str, dict]:
    """Return (version, entry) for ``component``; version None means latest release."""
    entries = manifest["signed"]["platforms"].get(platform)
    if entries is None:
        raise ValueError(f"{component}: no {platform} platform in manifest")
    v = version or latest_release(entries)
    e = entries.get(v)
    if e is None:
        raise ValueError(f"{component}: version {v} not published for {platform}")
    if e.get("yanked"):
        raise ValueError(f"{component} {v} is yanked; choose another version")
    for key in ("url", "length"):
        if key not in e:
            raise ValueError(f"{component} {v}: manifest entry lacks {key!r}")
    if "sha256" not in e.get("hashes", {}):
        raise ValueError(f"{component} {v}: manifest entry lacks a sha256")
    return v, e


def rows_for(tidb_version: str, manifests: dict[str, dict], tiup_versions: dict[str, str | None] | None = None):
    """Build [(component, version, platform, sha256, bytes, url)] from loaded manifests."""
    tiup_versions = tiup_versions or {}
    rows = []
    for comp in AT_TIDB_VERSION:
        v, e = pick_entry(manifests[comp], comp, tidb_version)
        rows.append((comp, v, PLATFORM, e["hashes"]["sha256"], e["length"], e["url"]))
    for comp in AT_LATEST:
        v, e = pick_entry(manifests[comp], comp, tiup_versions.get(comp))
        rows.append((comp, v, PLATFORM, e["hashes"]["sha256"], e["length"], e["url"]))
    return rows


def render(rows, mirror_version: int, today: str, mirror: str = MIRROR) -> str:
    out = HEADER.format(mirror=mirror, snapshot=mirror_version, today=today)
    for r in rows:
        out += "{}  {}  {}  {}  {}  {}\n".format(*r)
    return out


def parse(text: str):
    """Parse a VERSIONS file into [(component, version, platform, sha256, bytes, url)]."""
    rows = []
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split()
        if len(parts) != 6:
            raise ValueError(f"bad VERSIONS line: {line!r}")
        comp, ver, plat, sha, size, url = parts
        rows.append((comp, ver, plat, sha, int(size), url))
    return rows


def load_manifests(mirror: str) -> tuple[dict[str, dict], int]:
    timestamp_version = fetch_json(f"{mirror}/timestamp.json")["signed"]["version"]
    snapshot = fetch_json(f"{mirror}/snapshot.json")["signed"]
    manifests = {}
    for comp in AT_TIDB_VERSION + AT_LATEST:
        meta = snapshot["meta"].get(f"/{comp}.json")
        if meta is None:
            raise SystemExit(f"mirror snapshot has no manifest for {comp!r}")
        manifests[comp] = fetch_json(f"{mirror}/{meta['version']}.{comp}.json")
    return manifests, timestamp_version


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--tidb-version", required=True, help="e.g. v8.5.8 (an LTS patch release)")
    ap.add_argument("--tiup-version", help="default: latest release")
    ap.add_argument("--cluster-version", help="tiup-cluster; default: latest release")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--mirror", default=MIRROR)
    ap.add_argument("--check", action="store_true", help="compare the mirror to --out; exit 1 on any difference")
    args = ap.parse_args()

    if not semver(args.tidb_version):
        print(f"--tidb-version must look like v8.5.8, got {args.tidb_version!r}", file=sys.stderr)
        return 2
    manifests, snap = load_manifests(args.mirror)
    # --check compares against the pinned tiup/cluster versions rather than "latest".
    pins = {"tiup": args.tiup_version, "cluster": args.cluster_version}
    if args.check:
        old = parse(args.out.read_text())
        for comp, ver, *_ in old:
            if comp in AT_LATEST and not pins.get(comp):
                pins[comp] = ver
    rows = rows_for(args.tidb_version, manifests, pins)

    if args.check:
        if rows == old:
            print(f"OK: {args.out} matches the mirror ({len(rows)} artifacts)")
            return 0
        a, b = {r[0]: r for r in old}, {r[0]: r for r in rows}
        for comp in sorted(set(a) | set(b)):
            if a.get(comp) != b.get(comp):
                print(f"DIFF {comp}:\n  pinned: {a.get(comp)}\n  mirror: {b.get(comp)}", file=sys.stderr)
        return 1

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(rows, snap, date.today().isoformat(), args.mirror))
    total = sum(r[4] for r in rows)
    print(f"wrote {args.out} ({len(rows)} artifacts, {total / 1e6:.0f} MB total)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
