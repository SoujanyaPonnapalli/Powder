"""Render the TiUP cluster topology (plan §6, step 4 consumes it).

Inputs are the spec and a mapping name -> :class:`Host` (from ``state.json`` after deploy, or fake hosts in
tests). Every TiKV store gets the labels PD uses for isolation (``region``, ``zone``, ``host``) plus
``machine_class``, the library machine class that the failure emulator injects and that a patched PD or the
ILP oracle can read straight from store labels (plan §8).

The YAML schema follows TiUP's documented topology (``global``, ``server_configs``, ``pd_servers``,
``tikv_servers``, ``tidb_servers``, ``monitoring_servers``, ``grafana_servers``; per-instance
``config: {server.labels: ...}``). It is checked against a real cluster at gate G2.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

import yaml

from .spec import ClusterSpec, plan_nodes

LOCATION_LABELS = ["region", "zone", "host"]
DEPLOY_DIR = "/tidb-deploy"
DATA_DIR = "/tidb-data"
TIKV_DATA_DIR = "/data/tikv"      # instance-store NVMe mounted by node_bootstrap.sh
_LABEL_RE = re.compile(r"^[A-Za-z0-9]([-A-Za-z0-9_.]*[A-Za-z0-9])?$")


class TopologyError(ValueError):
    pass


@dataclass(frozen=True)
class Host:
    name: str
    private_ip: str
    region: str
    az: str


def label_value(raw: str) -> str:
    """Make ``raw`` a valid PD/TiKV label value (letters, digits, '-', '_', '.'; alphanumeric at both ends)."""
    v = re.sub(r"[^A-Za-z0-9_.-]", "_", raw).strip("_.-")
    if not v or not _LABEL_RE.match(v):
        raise TopologyError(f"cannot make a label value from {raw!r}")
    return v


def machine_class_label(machine_id: str) -> str:
    """``machine/ford10-google-storage`` -> ``ford10-google-storage``."""
    return label_value(machine_id.split("/", 1)[-1])


def topology_dict(spec: ClusterSpec, hosts: dict[str, Host]) -> dict:
    nodes = plan_nodes(spec)
    missing = [n.name for n in nodes if n.role in ("controller", "pd", "tikv", "tidb") and n.name not in hosts]
    if missing:
        raise TopologyError(f"no host for: {', '.join(missing)}")

    pd_cfg = {
        # tiup refuses TiKV labels missing from location-labels (G2); machine_class sits below host, which is already
        # unique per store, so it cannot change replica placement
        "replication.location-labels": LOCATION_LABELS + ["machine_class"],
        "replication.isolation-level": "region",
        "replication.max-replicas": spec.replication_factor,
    }
    pd_cfg.update(spec.pd_config)       # explicit spec settings win (e.g. schedule.max-store-down-time)
    topo: dict = {
        "global": {"user": "tidb", "ssh_port": 22, "deploy_dir": DEPLOY_DIR, "data_dir": DATA_DIR,
                   "arch": "amd64"},
        "server_configs": {"pd": pd_cfg, "tikv": dict(spec.tikv_config), "tidb": dict(spec.tidb_config)},
        "pd_servers": [], "tidb_servers": [], "tikv_servers": [],
    }
    for n in nodes:
        h = hosts.get(n.name)
        if n.role == "pd":
            topo["pd_servers"].append({"host": h.private_ip, "name": n.name})
        elif n.role == "tidb":
            topo["tidb_servers"].append({"host": h.private_ip})
        elif n.role == "tikv":
            topo["tikv_servers"].append({
                "host": h.private_ip,
                "data_dir": TIKV_DATA_DIR,
                "config": {"server.labels": {
                    "region": label_value(h.region),
                    "zone": label_value(h.az or h.region),
                    "host": label_value(n.name),
                    "machine_class": machine_class_label(n.machine or "unknown"),
                }},
            })
    ctl = hosts["controller"]
    topo["monitoring_servers"] = [{"host": ctl.private_ip}]
    topo["grafana_servers"] = [{"host": ctl.private_ip}]
    return topo


def render_topology(spec: ClusterSpec, hosts: dict[str, Host]) -> str:
    header = (f"# Generated by powder.deploy.topology for handle {spec.handle} (spec hash {spec.spec_hash()}).\n"
              f"# Do not edit by hand; change the spec and re-render.\n")
    return header + yaml.safe_dump(topology_dict(spec, hosts), sort_keys=False, default_flow_style=False)
