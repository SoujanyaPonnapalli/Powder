from .topology import Host

WORK_ROOT = "/tmp/powder-exp"
LOADGEN_BIN = "~/powder-bin/powder-load"
PROM_PORT = 9090
START_LEAD_S = 30.0


class ExperimentError(RuntimeError):
    pass


@dataclass(frozen=True)
class ScheduledAction:
    """Run ``command`` on ``node`` ``offset_s`` seconds after the load starts (the exec #8 injection hook)."""
    offset_s: float
    node: str
    command: str
    label: str = ""


SNAPSHOTTER = r"""#!/usr/bin/env bash
# PD Region-map snapshotter (generated by powder.deploy.experiment). usage: snapshotter.sh DIR PD_URL INTERVAL_S
D=$1; URL=$2; EVERY=$3
mkdir -p "$D/snapshots"
while [ ! -f "$D/stop" ]; do
  ts=$(date +%s.%N)
  curl -sf --max-time 20 "$URL/pd/api/v1/stores" | gzip > "$D/snapshots/.stores.tmp" && mv "$D/snapshots/.stores.tmp" "$D/snapshots/stores-$ts.json.gz"
  curl -sf --max-time 60 "$URL/pd/api/v1/regions" | gzip > "$D/snapshots/.regions.tmp" && mv "$D/snapshots/.regions.tmp" "$D/snapshots/regions-$ts.json.gz"
  sleep "$EVERY"
done
echo done > "$D/snap.done"
"""


def git_state(root: Path) -> dict:
    try:
        sha = subprocess.run(["git", "-C", str(root), "rev-parse", "HEAD"], capture_output=True, text=True, timeout=10).stdout.strip()
        dirty = bool(subprocess.run(["git", "-C", str(root), "status", "--porcelain", "--untracked-files=no"],
                                    capture_output=True, text=True, timeout=10).stdout.strip())
        return {"git_sha": sha, "git_dirty": dirty}
    except Exception:
        return {"git_sha": None, "git_dirty": None}


def nested_get(doc: dict, key: str):
    """Find a PD config key (``schedule.max-store-down-time`` or bare ``max-store-down-time``) in ``config show all``."""
    name = key.split(".")[-1]
    for section in ([key.split(".")[0]] if "." in key else []) + ["schedule", "replication", "pd-server"]:
        if isinstance(doc.get(section), dict) and name in doc[section]:
            return doc[section][name]
    return None


class Context:
    def __init__(self, spec: ClusterSpec, cfg: ExperimentConfig, rundir: RunDir, state: RunState, runner: Runner,
                 exp_dir: Path, exp_id: str, log: Callable[[str], None], sleep, clock, loadgen_bin: str, pdctl: str | None,
                 pd_url_override: str | None = None):
        self.spec, self.cfg, self.rundir, self.state, self.runner = spec, cfg, rundir, state, runner
        self.exp_dir, self.exp_id, self.log, self.sleep, self.clock = exp_dir, exp_id, log, sleep, clock
        self.errors: list[str] = []
        self.hosts = {n: Host(n, r.private_ip, r.region, r.az) for n, r in state.instances.items()}
        self.pd = pd_url_override or pd_url(spec, self.hosts)
        self.work = f"{WORK_ROOT}/{exp_id}"
        self.loadgen_bin = loadgen_bin
        v = pinned_versions()
        self.pdctl_prefix = pdctl or f"~/.tiup/bin/tiup ctl:{v['tidb']} pd"

    def ctl(self, command: str, timeout: float = 120, check: bool = True):
        return self.runner.run("controller", command, timeout=timeout, check=check)

    def pdctl(self, args: str, timeout: float = 60, check: bool = True):
        return self.ctl(f"{self.pdctl_prefix} -u {self.pd} {args} < /dev/null", timeout, check)

    def tidb_addr(self, region: str) -> str:
        for n in plan_nodes(self.spec):
            if n.role == "tidb" and n.region == region:
                return f"{self.hosts[n.name].private_ip}:{TIDB_PORT}"
        raise ExperimentError(f"no TiDB server in {region}")

    def soft(self, what: str, fn):
        """Run a collection step; record (never raise) its failure."""
        try:
            return fn()
        except (RemoteError, OSError, ValueError, tarfile.TarError) as e:
            self.errors.append(f"{what}: {e}")
            self.log(f"  collection problem ({what}): {str(e)[:200]}")


def _loadgens(ctx: Context):
    lg = ctx.state.by_role("loadgen")
    if not lg:
        raise ExperimentError("deployment has no load generator nodes")
    return lg


def apply_pd_runtime_config(ctx: Context) -> dict:
    """Set the experiment's PD options (pd-ctl), returning the previous values for restoration."""
    wanted = ctx.cfg.pd_runtime_config
    if not wanted:
        return {}
    doc = json.loads(ctx.pdctl("config show all").stdout)
    (ctx.exp_dir / "pd").mkdir(parents=True, exist_ok=True)
    (ctx.exp_dir / "pd" / "config-before.json").write_text(json.dumps(doc, indent=1))
    prev = {}
    for k, v in wanted.items():
        old = nested_get(doc, k)
        if old is None:
            raise ExperimentError(f"PD option {k!r} not found in `pd-ctl config show all`")
        prev[k] = old
        ctx.pdctl(f"config set {k.split('.')[-1]} {v}")
    return prev


def restore_pd_runtime_config(ctx: Context, prev: dict) -> None:
    for k, v in prev.items():
        ctx.soft(f"restore PD option {k}", lambda k=k, v=v: ctx.pdctl(f"config set {k.split('.')[-1]} {v}"))


def prepare_table(ctx: Context) -> dict:
    lg = _loadgens(ctx)[0]
    w = ctx.cfg.workload
    r = ctx.runner.run(lg.name, f"{ctx.loadgen_bin} prepare --dsn {ctx.tidb_addr(lg.region)} --keys {int(w.keys)} "
                                f"--regions {int(w.regions_target)}", timeout=900)
    info = json.loads(r.stdout.strip().splitlines()[-1])
    (ctx.exp_dir / "prepare.json").write_text(json.dumps(info, indent=1))
    return info


def settle_state(ctx: Context) -> tuple[int, int]:
    """(Regions missing a replica, running PD operators): both must be 0 before an experiment starts."""
    miss = json.loads(ctx.ctl(f"curl -sf --max-time 30 {ctx.pd}/pd/api/v1/regions/check/miss-peer", timeout=60).stdout)
    ops = json.loads(ctx.ctl(f"curl -sf --max-time 30 {ctx.pd}/pd/api/v1/operators", timeout=60).stdout)
    return int(miss.get("count", 0)), len(ops)


def wait_settled(ctx: Context, timeout: float, quiet_polls: int = 2, interval: float = 10.0) -> float:
    """Block until the cluster has finished (up-)replicating: a freshly deployed or freshly split cluster is still
    moving data, and that would be measured as repartitioning the experiment did not cause. Raises on timeout."""
    waited, calm = 0.0, 0
    while True:
        miss, ops = settle_state(ctx)
        calm = calm + 1 if (miss == 0 and ops == 0) else 0
        if calm >= quiet_polls:
            return waited
        if waited >= timeout:
            raise ExperimentError(f"cluster did not settle within {timeout:.0f}s ({miss} Regions missing a replica, "
                                  f"{ops} operators running); not starting the experiment")
        ctx.log(f"  waiting for the cluster to settle: {miss} Regions missing a replica, {ops} operators running")
        ctx.sleep(interval)
        waited += interval


def start_snapshotter(ctx: Context) -> None:
    script = ctx.exp_dir / "pd" / "snapshotter.sh"
    script.parent.mkdir(parents=True, exist_ok=True)
    script.write_text(SNAPSHOTTER)
    ctl = f"{ctx.work}/ctl"
    ctx.ctl(f"mkdir -p {ctl}")
    ctx.runner.put("controller", script, f"{ctl}/snapshotter.sh")
    ctx.ctl(f"cd {ctl} && rm -f stop snap.done && (nohup bash snapshotter.sh {ctl} {ctx.pd} {ctx.cfg.region_map_interval_s} "
            f">snapshotter.log 2>&1 &) ; sleep 1; echo started")


def stop_snapshotter(ctx: Context) -> None:
    ctl = f"{ctx.work}/ctl"
    ctx.ctl(f"touch {ctl}/stop")
    for _ in range(60):
        if ctx.ctl(f"test -f {ctl}/snap.done", check=False).returncode == 0:
            return
        ctx.sleep(2)
    raise RemoteError("snapshotter did not stop within 120 s")


def start_generators(ctx: Context, start_at: float) -> dict[str, str]:
    """Start probe + load on every load generator; returns node -> work dir."""
    c, w = ctx.cfg, ctx.cfg.workload
    dirs = {}
    for lg in _loadgens(ctx):
        d = f"{ctx.work}/{lg.name}"
        dirs[lg.name] = d
        dsn = ctx.tidb_addr(lg.region)
        common = f"--dsn {dsn} --region {lg.region} --keys {int(w.keys)} --start-at {start_at:.3f} --duration {int(w.duration_s)}s"
        probe = (f"{ctx.loadgen_bin} probe {common} --buckets {int(w.regions_target)} --interval {c.prober_interval_s}s "
                 f"--timeout {c.request_timeout_s}s --out {d}/probes.jsonl.gz")
        load = (f"{ctx.loadgen_bin} load {common} --rate {w.rate_per_region} --timeout {c.request_timeout_s}s "
                f"--key-dist {w.key_dist} --arrival {w.arrival} --seed {ctx.spec.seed} --out {d}/requests.jsonl.gz")
        cmd = f"mkdir -p {d} && cd {d} && rm -f *.done"
        for name, run in (("probe", probe), ("load", load)):
            inner = f"{run} > {d}/{name}.out 2> {d}/{name}.err; echo $? > {d}/{name}.done"
            cmd += f" && (nohup sh -c {shlex.quote(inner)} >/dev/null 2>&1 &)"
        ctx.runner.run(lg.name, cmd + " ; echo started", timeout=60)
    return dirs


def wait_generators(ctx: Context, dirs: dict[str, str], schedule: list[ScheduledAction], start_at: float,
                    controller_now: Callable[[], float]) -> list[dict]:
    """Poll for completion while executing ``schedule``; returns the applied-action log."""
    pending = sorted(schedule, key=lambda a: a.offset_s)
    applied: list[dict] = []
    deadline = start_at + ctx.cfg.workload.duration_s + 180
    while True:
        now = controller_now()
        while pending and now >= start_at + pending[0].offset_s:
            a = pending.pop(0)
            r = ctx.runner.run(a.node, a.command, timeout=120, check=False)
            applied.append({"label": a.label, "node": a.node, "command": a.command, "t_planned": start_at + a.offset_s,
                            "t_applied": now, "returncode": r.returncode, "stderr": r.stderr.strip()[:200]})
            ctx.log(f"  [t+{now - start_at:.0f}s] {a.label or a.command[:40]} on {a.node}: rc={r.returncode}")
        done = []
        for node, d in dirs.items():
            r = ctx.runner.run(node, f"cat {d}/load.done {d}/probe.done 2>/dev/null | wc -l", timeout=60, check=False)
            done.append(r.stdout.strip() == "2")
        if all(done) and not pending:
            return applied
        if now > deadline:
            raise ExperimentError("load generators did not finish before the deadline")
        ctx.sleep(2)


def collect_everything(ctx: Context, dirs: dict[str, str], t0: float, t1: float) -> None:
    exp, runner = ctx.exp_dir, ctx.runner
    ctl = f"{ctx.work}/ctl"
    for node, d in dirs.items():
        region = ctx.state.instances[node].region
        ctx.soft(f"fetch workload from {node}", lambda node=node, d=d, region=region: runner.get(
            node, f"{d}/", exp / "workload" / region))
        for name in ("load", "probe"):
            r = runner.run(node, f"cat {d}/{name}.done", timeout=30, check=False)
            if r.stdout.strip() not in ("0", ""):
                ctx.errors.append(f"{node}: {name} exited with status {r.stdout.strip()} (see workload/{region}/{name}.err)")
    ctx.soft("fetch PD snapshots", lambda: runner.get("controller", f"{ctl}/snapshots/", exp / "pd" / "snapshots"))

    def dumps():
        pdd = exp / "pd"
        pdd.mkdir(parents=True, exist_ok=True)
        for name, args in (("store", "store"), ("config", "config show all"), ("placement-rules", "config placement-rules show"),
                           ("operator-history", f"operator history {int(t0) - 5}")):
            r = ctx.pdctl(args, check=False)
            (pdd / f"{name}.json").write_text(r.stdout if r.returncode == 0 else json.dumps({"error": r.stderr.strip()}))
    ctx.soft("pd-ctl dumps", dumps)

    def prometheus():
        mdir = f"{ctl}/metrics"
        ctx.ctl(f"mkdir -p {mdir}")
        prom = f"http://{ctx.hosts['controller'].private_ip}:{PROM_PORT}/api/v1/query_range"
        lines = []
        for name, q in collect.METRICS.items():
            lines.append(f"curl -sfG {shlex.quote(prom)} --data-urlencode {shlex.quote('query=' + q)} --data-urlencode start={t0:.0f} "
                         f"--data-urlencode end={t1 + 15:.0f} --data-urlencode step=15 -o {mdir}/{name}.json --max-time 60 "
                         f"|| echo {name} >> {mdir}/FAILED")
        ctx.ctl("; ".join(lines), timeout=900, check=False)
        runner.get("controller", f"{mdir}/", exp / "metrics")
        failed = exp / "metrics" / "FAILED"
        if failed.exists():
            ctx.errors.append("Prometheus queries failed: " + ", ".join(failed.read_text().split()))
    ctx.soft("Prometheus export", prometheus)

    for n in plan_nodes(ctx.spec):
        if n.role not in ("pd", "tikv", "tidb"):
            continue

        def logs(n=n):
            tgz = f"{ctx.work}/logs-{n.name}.tgz"
            runner.run(n.name, f"sudo sh -c 'cd /tidb-deploy && tar czf {tgz} --ignore-failed-read $(ls -d */log)' && "
                               f"sudo chown $(id -u) {tgz}", timeout=300)
            dest = exp / "logs" / n.name
            dest.mkdir(parents=True, exist_ok=True)
            runner.get(n.name, tgz, dest / "logs.tgz")
            with tarfile.open(dest / "logs.tgz") as t:
                t.extractall(dest, filter="data")
        ctx.soft(f"logs from {n.name}", logs)


def run_experiment(spec: ClusterSpec, cfg: ExperimentConfig, rundir: RunDir, runner: Runner,
                   schedule: list[ScheduledAction] | None = None, log: Callable[[str], None] = print,
                   sleep=time.sleep, clock=time.time, loadgen_bin: str = LOADGEN_BIN, pdctl: str | None = None,
                   exp_id: str | None = None, pd_url_override: str | None = None, settle_timeout_s: float = 600.0,
                   settle_interval_s: float = 10.0) -> Path:
    if cfg.injector.startswith("trace:"):
        raise ExperimentError("injector 'trace:<file>' is reserved for exec #8 (the failure emulator) and not implemented yet")
    state = rundir.load_state()
    state.require_installed()
    stamp = time.strftime("%Y%m%dT%H%M%SZ", time.gmtime(clock()))
    exp_id = exp_id or f"{cfg.name}-{stamp}"
    exp = rundir.experiments_dir / exp_id
    if exp.exists():
        raise ExperimentError(f"{exp} already exists")
    (exp / "faults").mkdir(parents=True)
    ctx = Context(spec, cfg, rundir, state, runner, exp, exp_id, log, sleep, clock, loadgen_bin, pdctl, pd_url_override)
    (exp / "config.json").write_text(json.dumps({
        "experiment": cfg.to_dict(), "handle": state.handle, "spec_hash": spec.spec_hash(), "tidb_version": spec.tidb_version,
        "started_at": utcnow(), **git_state(Path(__file__).resolve().parents[2])}, indent=1, sort_keys=True))
    log(f"[{state.handle}] experiment {exp_id}")

    prev = apply_pd_runtime_config(ctx)
    snap_started = False
    try:
        log("  preparing table")
        prep = prepare_table(ctx)
        if settle_timeout_s > 0:
            waited = wait_settled(ctx, settle_timeout_s, interval=settle_interval_s)
            log(f"  cluster settled (waited {waited:.0f}s)")
        log("  starting PD snapshotter")
        start_snapshotter(ctx)
        snap_started = True
        now = float(ctx.ctl("date +%s.%N", timeout=30).stdout.strip())
        start_at = now + START_LEAD_S
        log(f"  starting {len(_loadgens(ctx))} load generator(s); {cfg.workload.duration_s:.0f}s at {cfg.workload.rate_per_region:g} req/s each")
        dirs = start_generators(ctx, start_at)
        offset = {"v": now - clock()}                              # controller clock minus ours
        applied = wait_generators(ctx, dirs, list(schedule or []), start_at, lambda: clock() + offset["v"])
        (exp / "faults" / "applied.jsonl").write_text("".join(json.dumps(a) + "\n" for a in applied))
        (exp / "faults" / "planned.jsonl").write_text("".join(json.dumps(a.__dict__) + "\n" for a in (schedule or [])))
    finally:
        if snap_started:
            ctx.soft("stop snapshotter", lambda: stop_snapshotter(ctx))
        restore_pd_runtime_config(ctx, prev)

    t1 = start_at + cfg.workload.duration_s
    log("  collecting results")
    collect_everything(ctx, dirs, start_at, t1)
    rf = spec.replication_factor
    from .pricing import transfer_entry_id
    usd = None
    try:
        from powder.faults import FaultLibrary
        from powder.faults.prices import transfer_per_gb
        lib = FaultLibrary.load()
        usd = max((transfer_per_gb(lib, transfer_entry_id(lib), a, b) for a in spec.regions for b in spec.regions if a != b),
                  default=None)
    except Exception as e:                                          # never block a finished experiment on pricing
        ctx.errors.append(f"transfer price lookup: {e}")
    try:
        summary = collect.summarize_experiment(exp, cfg, int(prep["table_id"]), rf, inter_region_usd_per_gb=usd)
    except ValueError as e:
        ctx.errors.append(f"summary: {e}")
        summary = {"error": str(e)}
    summary["handle"] = state.handle
    summary["experiment_id"] = exp_id
    summary["collection_errors"] = list(summary.get("collection_errors", [])) + ctx.errors
    summary["injector"] = cfg.injector
    collect.write_summary(exp, summary)
    state.experiments.append(exp_id)
    state.save(rundir.state_path)
    rundir.update_manifest(last_experiment=exp_id, experiments=state.experiments)
    log(f"[{state.handle}] done: {exp / 'summary.json'}")
    return exp
