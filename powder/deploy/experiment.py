"""Stage 4: run one experiment on an installed deployment and collect everything (plan §7).

``run_experiment`` never creates infrastructure: it needs a handle whose install stage is ``done``. Sequence:

1. apply ``pd_runtime_config`` (recorded and restored afterwards) and ``powder-load prepare`` (table pre-split into
   one Raft Region per target partition);
2. start the PD snapshotter on the controller (Region map + stores every ``region_map_interval``), then the per-region
   probers and open-loop load generators on every load-generator node, synchronised to a common ``--start-at``;
3. run ``schedule`` (timed commands on nodes: the fault-injection hook for exec #8, used today by the metric
   self-test) while waiting for the generators to finish;
4. stop the snapshotter, then collect: request/probe logs, snapshots, PD/TiKV/TiDB logs, ``pd-ctl`` dumps, Prometheus
   exports; compute ``summary.json``.

Collection problems are recorded in ``summary.json["collection_errors"]`` and never abort a finished experiment.
Commands run through a :class:`~powder.deploy.remote.Runner`, so the identical code is exercised locally in tests.
"""

from __future__ import annotations

