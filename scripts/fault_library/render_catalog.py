"""Render docs/fault_library.md from the library (deterministic).

    python scripts/fault_library/render_catalog.py
"""

from __future__ import annotations

import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from powder.faults import FaultLibrary  # noqa: E402
from powder.faults.assign import reliability_score  # noqa: E402
from powder.faults.convert import transient_and_permanent  # noqa: E402
from powder.faults.dists import from_spec  # noqa: E402
from powder.faults.planned_downtime import as_transient, long_run_fraction  # noqa: E402
from powder.faults.schema import pick  # noqa: E402

H = 8766.0


def fmt_years(rate_per_s: float) -> str:
    if rate_per_s <= 0:
        return "never"
    y = 1.0 / (rate_per_s * 3600 * H)
    return f"{y:.3g} y" if y >= 1 else f"{y * 365.25:.3g} d"


def fmt_s(s: float) -> str:
    if s < 120:
        return f"{s:.3g} s"
    if s < 7200:
        return f"{s / 60:.3g} min"
    return f"{s / 3600:.3g} h"


def main() -> int:
    lib = FaultLibrary.load()
    out = ["# Fault library catalogue", "",
           "Generated by `scripts/fault_library/render_catalog.py` from `data/fault_library/`. Do not edit by hand.",
           "Rates are per node; MTBF/MTTDL at the central level; availability counts node-level causes only "
           "(planned downtime and region outages are scenario-level and listed separately).", ""]

    out += ["## Node fault profiles", "",
            "| Profile | Tier | MTBF (transient) | Mean recovery | MTTDL (data loss) | Unavailable h/yr (R=1h) | Node availability |",
            "|---|---|---|---|---|---|---|"]
    for p in sorted(lib.query(kind="node"), key=lambda p: (p["tier"], p["id"])):
        lam_t, rec, lam_p = transient_and_permanent(p)
        score = reliability_score(p)
        avail = 1 - score / H
        out.append(f"| `{p['id']}` | {p['tier']} | {fmt_years(lam_t)} | {fmt_s(rec.mean)} | {fmt_years(lam_p)} | "
                   f"{score:.3g} | {avail:.6f} |")

    out += ["", "## Components (never priced; ingredients of node profiles)", "",
            "| Component | Rate low / central / high (per year) |", "|---|---|"]
    for c in sorted(lib.query(kind="component"), key=lambda c: c["id"]):
        r = c["rate_per_hour"]
        out.append(f"| `{c['id']}` | {r['low'] * H:.3g} / {r['central'] * H:.3g} / {r['high'] * H:.3g} |")

    out += ["", "## Planned downtime", "", "| Profile | Mean gap | Mean duration | Long-run fraction | h per node-year |",
            "|---|---|---|---|---|"]
    for p in sorted(lib.query(kind="planned_downtime"), key=lambda p: p["id"]):
        rate, md = as_transient(p)
        f = long_run_fraction(p)
        out.append(f"| `{p['id']}` | {1 / rate / 86400:.3g} d | {fmt_s(md)} | {f:.4%} | {f * H:.3g} |")

    out += ["", "## Region outages (per AWS region)", "",
            "| Profile | AWS region | Azure region | Outages per year (low / central / high) | Mean duration |",
            "|---|---|---|---|---|"]
    for p in sorted(lib.query(kind="region_outage"), key=lambda p: p["id"]):
        d = from_spec(p["duration"]["central"]).mean
        for aws, r in sorted(p["regions"].items()):
            q = r["rate_per_hour"]
            out.append(f"| `{p['id']}` | {aws} | {r['azure_region']} | "
                       f"{q['low'] * H:.3g} / {q['central'] * H:.3g} / {q['high'] * H:.3g} | {fmt_s(d)} |")
        if p.get("global"):
            q = p["global"]["rate_per_hour"]
            out.append(f"| `{p['id']}` | **all regions at once** | global process ({p['global']['n_incidents']} incident) | "
                       f"{q['low'] * H:.3g} / {q['central'] * H:.3g} / {q['high'] * H:.3g} | {fmt_s(d)} |")

    machines = sorted(lib.query(kind="machine"), key=lambda m: m["id"])
    out += ["", "## Machine classes", "", "| Machine | Fault profile | Tier | Price route | Regions |", "|---|---|---|---|---|"]
    for m in machines:
        out.append(f"| `{m['id']}` | `{m['fault_profile']}` | {m.get('tier', '')} | {m['price']['route']} | "
                   f"{', '.join(m.get('regions', []))} |")

    prices = lib.query(kind="price")
    dists = [p for p in prices if p.get("price_kind") == "price_distribution"]
    assigns = [p for p in prices if p.get("price_kind") == "price_assignment"]
    out += ["", "## Prices", ""]
    if not dists:
        out += ["No AWS prices fetched yet: run `fetch_aws_prices.py`, `fetch_spot.py advisor|history`, "
                "`build_prices.py`, then `build_machines.py` (see `infra/aws/README.md`).", ""]
    for d in sorted(dists, key=lambda d: d["id"]):
        s = d["summary"]
        out.append(f"- `{d['id']}`: n={d['n']}, $/h min {s['min']:.3f}, median {s['p50']:.3f}, max {s['max']:.3f}")
    if assigns:
        out += ["", f"{len(assigns)} price assignments (rho = 0 over 20 seeds, rho = 0.5, rho = 1)."]

    covered = {m["fault_profile"] for m in machines}
    scen_ids = ", ".join("`" + s["id"] + "`" for s in sorted(lib.query(kind="scenario"), key=lambda s: s["id"]))
    unpriced = [p["id"] for p in lib.query(kind="node") if p["id"] not in covered]
    out += ["", "## Coverage", "",
            "- Node profiles without a machine class: " + (", ".join("`" + u + "`" for u in unpriced) or "none"),
            f"- Machine classes with assigned (not native) prices: "
            f"{sum(m['price']['route'] == 'assigned' for m in machines)}",
            f"- Scenarios: {scen_ids}",
            ""]
    path = ROOT / "docs/fault_library.md"
    path.write_text("\n".join(out))
    print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
